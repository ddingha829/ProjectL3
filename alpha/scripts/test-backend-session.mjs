import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {build} from 'esbuild';

await fs.mkdir('.test-data',{recursive:true});
const outfile=path.resolve('.test-data/backend-session.mjs');
await build({entryPoints:['src/unified/backendSession.ts'],outfile,bundle:true,platform:'node',format:'esm',logLevel:'silent'});
const {backendSessionKey}=await import(pathToFileURL(outfile));
const session='l2_unified_preview_session_v1',generation='l2_unified_backend_generation_v1';
const values=new Map([[session,'demo login'],['l2_unified_ui_v1','demo records'],['l2_unified_account_pending:old','unsynced'],['l2_unified_supabase_auth_v1','old JWT']]);
const storage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value),removeItem:key=>values.delete(key)};
assert.equal(backendSessionKey(undefined,storage),'l2_unified_supabase_auth_v1');
assert.equal(values.get(session),'demo login');
for(const invalid of ['',{},'contains spaces','x'.repeat(65)])assert.equal(backendSessionKey(invalid,storage),'l2_unified_supabase_auth_v1');
const newKey=backendSessionKey('alpha-fresh-1',storage);
assert.notEqual(newKey,'l2_unified_supabase_auth_v1');
assert.equal(values.has(session),false);
assert.equal(values.get(generation),'alpha-fresh-1');
assert.equal(values.get('l2_unified_ui_v1'),'demo records');
assert.equal(values.get('l2_unified_account_pending:old'),'unsynced');
assert.equal(values.get('l2_unified_supabase_auth_v1'),'old JWT');
values.set(session,'explicit new demo login');
assert.equal(backendSessionKey('alpha-fresh-1',storage),newKey);
assert.equal(values.get(session),'explicit new demo login');
assert.notEqual(backendSessionKey('alpha-fresh-2',storage),newKey);
assert.equal(values.has(session),false);
console.log('Backend reset session isolation: 16 assertions passed; local records preserved.');
