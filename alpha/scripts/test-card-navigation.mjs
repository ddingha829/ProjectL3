import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {build} from 'esbuild';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
await fs.mkdir('.test-data',{recursive:true});
const outfile=path.resolve('.test-data/card-navigation.mjs');
await build({entryPoints:['src/unified/cardNavigation.ts'],outfile,bundle:true,platform:'node',format:'esm',logLevel:'silent'});
const {isCardBackSwipe,cardHistoryId,cardHistoryState}=await import(pathToFileURL(outfile));
const checks=[];const test=(name,run)=>{run();checks.push(name);};
test('right flick goes back',()=>assert.equal(isCardBackSwipe(60,5,200,390),true));
test('deliberate right drag goes back',()=>assert.equal(isCardBackSwipe(120,10,800,390),true));
test('left swipe never goes back',()=>assert.equal(isCardBackSwipe(-120,5,200,390),false));
test('vertical comment gesture stays vertical',()=>assert.equal(isCardBackSwipe(15,100,200,390),false));
test('diagonal movement does not dismiss',()=>assert.equal(isCardBackSwipe(80,70,200,390),false));
test('small tap does not dismiss',()=>assert.equal(isCardBackSwipe(5,2,100,390),false));
test('slow short gesture springs back',()=>assert.equal(isCardBackSwipe(60,2,700,390),false));
test('invalid measurements cannot navigate',()=>assert.equal(isCardBackSwipe(Infinity,0,100,390),false));
test('card entry retains Next router state without mutating it',()=>{const original={__NA:true,tree:['app'],custom:'keep'},next=cardHistoryState(original,'card-a');assert.equal(cardHistoryId(original),'');assert.equal(cardHistoryId(next),'card-a');assert.equal(next.__NA,true);assert.deepEqual(next.tree,original.tree);assert.equal(next.custom,'keep');});
test('closing removes only the card marker',()=>{const next=cardHistoryState(cardHistoryState({__NA:true,custom:'keep'},'card-a'),'');assert.equal(cardHistoryId(next),'');assert.deepEqual(next,{__NA:true,custom:'keep'});});
test('invalid history state is ignored',()=>{for(const state of [null,undefined,12,'card-a',{},[]])assert.equal(cardHistoryId(state),'');});
console.log(JSON.stringify({status:'passed',checks}));
