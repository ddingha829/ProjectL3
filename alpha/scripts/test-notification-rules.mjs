import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {build} from 'esbuild';
import assert from 'node:assert/strict';
await fs.mkdir('.test-data',{recursive:true});const file=path.resolve('.test-data/notification-rules.mjs');
await build({entryPoints:['src/unified/notificationRules.ts'],outfile:file,bundle:true,platform:'node',format:'esm',logLevel:'silent'});
const {nearbyCandidate,notificationTarget,validPushSubscription,NEARBY_COOLDOWN_MS}=await import(pathToFileURL(file));
const base={id:'one',authorId:'friend',createdAt:1,place:{id:'place',name:'Cafe',area:'',lat:37.5,lng:127}},point={lat:37.5,lng:127,accuracy:20},prefs={newLogs:false,nearby:true,lastNearbyAt:null,seenLogIds:[]};
assert.equal(nearbyCandidate([base],point,prefs).id,'one');
assert.equal(nearbyCandidate([{...base,authorId:'me'}],point,prefs),undefined);
assert.equal(nearbyCandidate([base],{...point,accuracy:200},prefs),undefined);
assert.equal(nearbyCandidate([base],{...point,lat:38},prefs),undefined);
assert.equal(nearbyCandidate([base],point,{...prefs,seenLogIds:['one']}),undefined);
assert.equal(nearbyCandidate([base],point,{...prefs,lastNearbyAt:100},100+NEARBY_COOLDOWN_MS-1),undefined);
assert.equal(nearbyCandidate([base],point,{...prefs,lastNearbyAt:100},100+NEARBY_COOLDOWN_MS).id,'one');
assert.equal(nearbyCandidate([base],point,{...prefs,nearby:false}),undefined);
assert.equal(nearbyCandidate([base],{...point,lat:NaN},prefs),undefined);
const id='12345678-1234-4234-8234-123456789012',group='87654321-1234-4234-8234-123456789012';
assert.deepEqual(notificationTarget(`/?view=map&scope=${group}&focus=${id}`),{kind:'map',scope:group,logId:id});
assert.equal(notificationTarget(`https://evil.invalid/?view=map&scope=${group}&focus=${id}`),null);
assert.equal(notificationTarget('/?view=map&scope=mine&focus=not-a-uuid'),null);
const sub={endpoint:'https://fcm.googleapis.com/fcm/send/fixture',keys:{p256dh:'A'.repeat(87),auth:'B'.repeat(22)}};
assert.equal(validPushSubscription(sub),true);
for(const endpoint of ['https://localhost/internal','http://fcm.googleapis.com/fcm/send/x','https://fcm.googleapis.com.evil.invalid/x','https://fcm.googleapis.com:444/x','https://user@fcm.googleapis.com/x'])assert.equal(validPushSubscription({...sub,endpoint}),false);
assert.equal(validPushSubscription({...sub,keys:{p256dh:'bad',auth:'bad'}}),false);
console.log('Notification rules: 19 nearby, cooldown, deep-link and endpoint assertions passed.');
