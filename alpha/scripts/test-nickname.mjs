import assert from 'node:assert/strict';
import {build} from 'esbuild';
const result=await build({stdin:{contents:"export * from './src/unified/nickname'; export {persistNickname,emptyCloudState,cloudOperations} from './src/unified/cloudRepository';",resolveDir:process.cwd()},bundle:true,platform:'node',format:'esm',write:false,logLevel:'silent'});
const {normalizeNickname,nicknameInitial,persistNickname,emptyCloudState,cloudOperations}=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'));
assert.equal(normalizeNickname('  티끌 친구  '),'티끌 친구');
assert.equal(normalizeNickname('\u1100\u1161'),'가');
for(const invalid of ['  ','a'.repeat(31),'이름\n사이'])assert.throws(()=>normalizeNickname(invalid));
assert.equal(nicknameInitial('🌿친구'),'🌿');
let calls=[];const client={rpc:async(name,args)=>{calls.push({name,args});return {error:null};}};
const before={...emptyCloudState(),serverPreferencesRevision:4};
const next=await persistNickname(client,before,'  친구  ');
assert.equal(before.nicknameConfigured,undefined);
assert.equal(next.nicknameConfigured,true);assert.equal(next.people[0].name,'친구');assert.equal(next.serverPreferencesRevision,5);
assert.deepEqual(calls[0].args.p_operations.map(o=>o.kind),['profile','preferences']);
assert.deepEqual(calls[0].args.p_operations[1].payload.presets,before.presets);
assert.equal(calls[0].args.p_operations[1].expected,4);
assert.equal(cloudOperations(next,{...next,people:next.people.map(p=>({...p,name:'다른 이름'}))})[0].kind,'profile');
const repeat=await persistNickname(client,next,'친구');assert.equal(calls.length,1);assert.equal(repeat.serverPreferencesRevision,5);
await assert.rejects(()=>persistNickname({rpc:async()=>({error:Error('offline')})},before,'실패'),/offline/);
assert.equal(before.nicknameConfigured,undefined);
await persistNickname(client,before,'나');assert.deepEqual(calls.at(-1).args.p_operations.map(o=>o.kind),['preferences']);
console.log(JSON.stringify({status:'passed',checks:20}));
